import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts',{recursive:true});

const browser = await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const base=process.env.PROTOTYPE_URL || 'http://127.0.0.1:5173';
try {
  await page.goto(base);
  await page.waitForSelector('#ral');
  assert.equal(await page.locator('#ral').inputValue(),'28750');
  assert.equal(await page.locator('#age').inputValue(),'25');
  assert.equal(await page.locator('#retirementAge').inputValue(),'67');
  assert.equal(await page.locator('#salaryGrowth').inputValue(),'0');
  assert.match(await page.locator('body').innerText(),/Cometa/);
  assert.match(await page.locator('body').innerText(),/Allianz/);
  assert.ok(await page.locator('svg').count() >= 3,'Projection and insight charts should render');
  assert.ok(await page.locator('table').count() >= 2,'Accessible chart and historical tables');
  assert.equal(await page.evaluate(()=>localStorage.length),0);
  assert.equal(await page.evaluate(()=>sessionStorage.length),0);
  const terminal = async (fund='cometa') => page.locator(`#${fund}-terminal`).innerText();
  const baseCometa=await terminal();
  const baseAllianz=await terminal('allianz');
  await page.locator('[data-scenario="optimistic"]').click();
  assert.notEqual(await terminal(),baseCometa,'Optimistic scenario must change projection');
  await page.locator('[data-scenario="conservative"]').click();
  assert.notEqual(await terminal(),baseCometa,'Conservative scenario must change projection');
  await page.locator('[data-scenario="central"]').click();
  assert.equal(await terminal(),baseCometa);
  await page.locator('#salaryGrowth').fill('2');
  await page.locator('#salaryGrowth').dispatchEvent('change');
  assert.notEqual(await terminal(),baseCometa,'Salary growth must affect balance');
  await page.locator('#reset').click();
  assert.equal(await terminal(),baseCometa);
  await page.locator('#cometa-mode').selectOption('tfr');
  assert.notEqual(await terminal(),baseCometa,'TFR-only changes Cometa');
  assert.equal(await terminal('allianz'),baseAllianz,'Cometa edits leave Allianz intact');
  await page.locator('#allianz-mode').selectOption('tfr');
  assert.notEqual(await terminal('allianz'),baseAllianz,'Independent Allianz TFR-only works');
  await page.locator('#reset').click();
  await page.locator('#cometa-mode').selectOption('fixed');
  await page.locator('#cometa-value').fill('100');
  await page.locator('#cometa-value').dispatchEvent('change');
  assert.notEqual(await terminal(),baseCometa);
  await page.locator('#reset').click();
  const currentReturns=await page.locator('#allianz-central').inputValue();
  await page.locator('#allianz-compartment').selectOption('azionaria');
  assert.match(await page.locator('#risk-warning').innerText(),/Rischi differenti/);
  assert.equal(await page.locator('#allianz-central').inputValue(),currentReturns,'Risk selection preserves user return assumptions');
  assert.match(await page.locator('#history').innerText(),/2008/,'Selected history changes with compartment');
  await page.locator('#reset').click();
  assert.equal((await page.locator('#risk-warning').innerText()).trim(),'');
  const beforeTax=await terminal();
  await page.locator('#marginalTaxRate').fill('23');
  await page.locator('#marginalTaxRate').dispatchEvent('change');
  assert.equal(await terminal(),beforeTax,'Personal tax benefit must not enter fund capital');
  const annualDetails=page.locator('details').filter({has:page.locator('summary', {hasText:'Tabella annuale accessibile'})});
  await annualDetails.locator('summary').click();
  assert.equal(await annualDetails.locator('tbody tr').count(),43,'Opening year plus 42 projected years');
  assert.doesNotMatch(await annualDetails.innerText(),/Non stimato/,'Tax benefit supplied in annual table');
  const annualRows=annualDetails.locator('tbody tr');
  assert.equal(await annualRows.nth(1).locator('td').nth(3).innerText(),await annualRows.nth(2).locator('td').nth(3).innerText(),'Constant salary implies same annual benefit in years 1 and 2');
  await page.locator('#marginalTaxRate').fill('101');
  await page.locator('#marginalTaxRate').dispatchEvent('change');
  assert.ok(!await page.locator('#cometa-terminal').isVisible(),'Tax above100% invalidates results');
  await page.locator('#marginalTaxRate').fill('23');
  await page.locator('#marginalTaxRate').dispatchEvent('change');
  await page.locator('#retirementAge').fill('24');
  await page.locator('#retirementAge').dispatchEvent('change');
  assert.ok(await page.locator('#errors').isVisible(),'Invalid age errors visible');
  assert.ok(!await page.locator('#cometa-terminal').isVisible(),'Stale capital hidden while invalid');
  await page.locator('#retirementAge').fill('67');
  await page.locator('#retirementAge').dispatchEvent('change');
  assert.ok(await page.locator('#cometa-terminal').isVisible(),'Valid recovery');
  await page.locator('#cometa-conservative').fill('99');
  await page.locator('#cometa-conservative').dispatchEvent('change');
  assert.ok(!await page.locator('#cometa-terminal').isVisible(),'Disordered scenarios cannot leave results');
  await page.locator('#reset').click();
  assert.equal(await page.locator('#cometa-central').inputValue(),'4');
  assert.equal(await page.locator('#cometa-conservative').inputValue(),'1');
  assert.equal(await page.locator('[data-scenario="central"]').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('#marginalTaxRate').inputValue(),'');
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
  const dimensions=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(dimensions.scroll<=dimensions.width+1,`Mobile horizontal overflow: ${JSON.stringify(dimensions)}`);
  await page.locator('#ral').fill('30000');
  await page.locator('#ral').dispatchEvent('change');
  assert.notEqual(await terminal(),baseCometa,'Mobile controls usable');
  await page.reload();
  assert.equal(await page.locator('#ral').inputValue(),'28750','Profile is not persisted');
  assert.deepEqual(errors,[]);
  assert.ok(await page.locator('a[href^="https://"]').count()>=2,'Visible history sources available');
  await page.locator('summary', {hasText:'Fonti e documenti consultati'}).click();
  assert.ok(await page.locator('.source-list a').count()>=8,'Versioned source register available');
  assert.match(await page.locator('.source-list').first().innerText(),/2026-07-31/);
  assert.match(await page.locator('.source-list').first().innerText(),/2026-10-31/);
  for(const link of await page.locator('.source-list a').all()) assert.match(await link.getAttribute('href'),/^https:\/\//);
  assert.equal(await page.evaluate(()=>localStorage.length+sessionStorage.length),0);
  console.log('Desktop/mobile browser acceptance passed: scenarios, independent strategies, risk, taxes, annual table, invalidation, reset, sources and no persistence.');
} finally { await browser.close(); }
